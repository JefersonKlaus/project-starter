"""The generated Terraform parsed with python-hcl2, as a flat list of blocks.

python-hcl2 keeps the HCL forms apart: a string literal comes back quoted ('"zip"'),
an expression wrapped in ${...} ('${aws_iam_role.x.arn}') and nested blocks as lists
of dicts. The helpers below read those forms.
"""

import json
import posixpath
import re
from dataclasses import dataclass, field

try:  # pure Python; listed in ai_create/requirements.txt
    import hcl2
except ImportError:  # pragma: no cover - only when the dependency is missing
    hcl2 = None

# Addresses a Terraform expression can refer to. The lookbehind keeps
# data.aws_x.y from also matching as the resource aws_x.y.
REFERENCE = re.compile(
    r"(?<![\w.\-/:])("
    r"data\.[A-Za-z_][\w-]*\.[A-Za-z_][\w-]*"
    r"|var\.[A-Za-z_][\w-]*"
    r"|local\.[A-Za-z_][\w-]*"
    r"|module\.[A-Za-z_][\w-]*"
    r"|aws_[a-z0-9_]+\.[A-Za-z_][\w-]*"
    r")"
)
_BLOCK_TYPES_WITH_TWO_LABELS = ("resource", "data")
_BLOCK_TYPES_WITH_ONE_LABEL = ("variable", "output", "module", "provider")


def unquote(key):
    return key[1:-1] if len(key) >= 2 and key[0] == key[-1] == '"' else key


def literal(value):
    """The text of a string literal ('"abc"' -> 'abc'); None for anything else."""
    if isinstance(value, str) and len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1]
    return None


def expression(value):
    """The expression of a ${...} value ('${var.x}' -> 'var.x'); None for anything else."""
    if isinstance(value, str) and value.startswith("${") and value.endswith("}"):
        return value[2:-1]
    return None


def references(value):
    """Addresses referred to anywhere inside a value (dicts and lists included)."""
    text = value if isinstance(value, str) else json.dumps(value)
    return set(REFERENCE.findall(text))


def nested_blocks(body, name):
    """Nested blocks (e.g. environment, attribute) as a list of dicts."""
    value = body.get(name) if isinstance(body, dict) else None
    if isinstance(value, dict):
        return [value]
    return [item for item in value or [] if isinstance(item, dict)]


def dynamic_block_names(body):
    """Names of the nested blocks generated by `dynamic "<name>" { ... }`."""
    names = set()
    for entry in nested_blocks(body, "dynamic"):
        names |= {unquote(key) for key in entry if key != "__is_block__"}
    return names


@dataclass
class TerraformBlock:
    kind: str  # resource, data, variable, output, module, provider, locals, terraform
    type: str  # resource/data type ("aws_lambda_function"), else None
    name: str  # label ("create_task"), else None
    file: str  # project path of the .tf file
    body: dict

    @property
    def address(self):
        if self.kind == "resource":
            return f"{self.type}.{self.name}"
        if self.kind == "data":
            return f"data.{self.type}.{self.name}"
        if self.kind == "variable":
            return f"var.{self.name}"
        if self.kind in ("output", "module", "provider"):
            return f"{self.kind}.{self.name}"
        return self.kind

    @property
    def label(self):
        return self.address

    @property
    def module_dir(self):
        return posixpath.dirname(self.file)

    def get(self, attribute):
        return self.body.get(attribute)

    def literal(self, attribute):
        return literal(self.body.get(attribute))

    def expression(self, attribute):
        return expression(self.body.get(attribute))

    def references(self):
        return references({k: v for k, v in self.body.items() if k != "__is_block__"})


@dataclass
class TerraformProject:
    blocks: list = field(default_factory=list)
    syntax_errors: dict = field(default_factory=dict)  # file -> message
    locals: dict = field(default_factory=dict)  # local name -> file
    duplicate_locals: list = field(default_factory=list)

    def of(self, kind, type_=None):
        return [
            b
            for b in self.blocks
            if b.kind == kind and (type_ is None or b.type == type_)
        ]

    def find(self, address):
        return next((b for b in self.blocks if b.address == address), None)

    @property
    def declared(self):
        """Every address an expression can refer to."""
        addresses = {b.address for b in self.blocks if b.kind in ("resource", "data")}
        addresses |= {
            b.address for b in self.blocks if b.kind in ("variable", "module")
        }
        addresses |= {f"local.{name}" for name in self.locals}
        return addresses


_POSITION_SUFFIX = re.compile(r"\s+at line \d+,? column \d+\.?$")


def _syntax_message(error):
    """'line 23, column 17: Unexpected token ...' (lark repeats the position at the end)."""
    lines = str(error).strip().splitlines()
    text = _POSITION_SUFFIX.sub("", lines[0]) if lines else type(error).__name__
    line = getattr(error, "line", None)
    column = getattr(error, "column", None)
    return f"line {line}, column {column}: {text}" if line else text


def parse_project(files):
    """Parse every .tf file of {project path: content}."""
    project = TerraformProject()
    for path in sorted(p for p in files if p.endswith(".tf")):
        if hcl2 is None:
            project.syntax_errors[path] = "python-hcl2 is not installed"
            continue
        try:
            parsed = hcl2.loads(files[path] or "")
        except Exception as e:  # lark raises several exception types
            project.syntax_errors[path] = _syntax_message(e)
            continue
        for kind, entries in parsed.items():
            for entry in entries if isinstance(entries, list) else [entries]:
                project.blocks.extend(_blocks_of(kind, entry, path, project))
    return project


def _blocks_of(kind, entry, path, project):
    if not isinstance(entry, dict):
        return
    if kind in _BLOCK_TYPES_WITH_TWO_LABELS:
        for type_key, named in entry.items():
            for name_key, body in (named or {}).items():
                if isinstance(body, dict):
                    yield TerraformBlock(
                        kind, unquote(type_key), unquote(name_key), path, body
                    )
    elif kind in _BLOCK_TYPES_WITH_ONE_LABEL:
        for name_key, body in entry.items():
            if isinstance(body, dict):
                yield TerraformBlock(kind, None, unquote(name_key), path, body)
    elif kind == "locals":
        for name in entry:
            if name == "__is_block__":
                continue
            if name in project.locals:
                project.duplicate_locals.append(name)
            project.locals.setdefault(name, path)
        yield TerraformBlock(kind, None, None, path, entry)
    else:  # terraform, moved, import, check...
        yield TerraformBlock(kind, None, None, path, entry)
